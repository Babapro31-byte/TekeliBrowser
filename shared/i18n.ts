const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, tr };

export function resolveLang(setting: 'auto' | Lang, systemLocale: string): Lang {
  if (setting !== 'auto') return setting;
  return systemLocale.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}

export function t(lang: Lang, key: MessageKey): string {
  return dictionaries[lang][key] ?? en[key] ?? key;
}
